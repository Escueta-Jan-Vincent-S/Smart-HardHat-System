# SITE CODE AND SUPERVISOR PIN GENERATORS
# ============================================================

def generate_site_prefix(site_name):
    cleaned_name = ""

    for character in site_name.upper():
        if character in string.ascii_uppercase:
            cleaned_name += character

    if len(cleaned_name) >= 3:
        return cleaned_name[:3]

    return (cleaned_name + "SMS")[:3]


def generate_site_code(site_name):
    prefix = generate_site_prefix(site_name)
    first_number = secrets.randbelow(900) + 100
    second_number = secrets.randbelow(9000) + 1000
    return f"{prefix}-{first_number}-{second_number}"


def generate_supervisor_pin():
    return str(secrets.randbelow(900000) + 100000)


def serialize_site(site):
    if site is None:
        return None

    return {
        "id": site["id"],
        "site_name": site["site_name"],
        "site_code": site["site_code"],
        "site_location": site["site_location"],
        "status": site["status"],
        "created_at": site["created_at"],
    }


def normalized_status(value):
    return str(value or "").strip().lower().replace("-", "_").replace(" ", "_")


def is_known_status(value):
    return normalized_status(value) not in {
        "",
        "unknown",
        "unmonitored",
        "not_monitored",
        "n_a",
        "na",
        "none",
        "pending",
    }


def is_compliant_status(value):
    return normalized_status(value) in {
        "present",
        "compliant",
        "ok",
        "yes",
        "true",
        "1",
        "detected",
        "safe",
    }


def display_drowsiness_status(value):
    status = normalized_status(value)

    if status in {"normal", "awake", "not_drowsy", "alert"}:
        return "Awake"

    if "drowsy" in status or "drowsiness" in status:
        return "Drowsy"

    return "Unmonitored"


def display_device_status(value):
    status = normalized_status(value)

    if status in {"online", "connected", "active"}:
        return "Online"

    if status in {"offline", "disconnected"}:
        return "Offline"

    return "Unmonitored"


def display_zone(floor, zone):
    if floor is None or zone is None:
        return "Unmonitored"

    floor_text = str(floor).strip()
    zone_text = str(zone).strip()

    if not floor_text or not zone_text:
        return "Unmonitored"

    if not floor_text.lower().startswith("floor"):
        floor_text = f"Floor {floor_text}"

    if not zone_text.lower().startswith("zone"):
        zone_text = f"Zone {zone_text}"

    return f"{floor_text}: {zone_text}"


